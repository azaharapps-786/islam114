  // ===================== CORE ANALYSIS METHOD =====================
  static Map<String, dynamic> analyzeText(String inputText) {
    if (inputText.trim().isEmpty) {
      return {'category': 'Uncategorized', 'score': 0, 'reference': '', 'severity': 'Neutral', 'explanation': ''};
    }
    String text = _preprocessText(inputText);

    bool isNegated = RegExp(
      r"\b(not|no|didn't|did not|don't|do not|never|avoided|stopped|quit|refrained from)\b",
      caseSensitive: false,
    ).hasMatch(text);

    if (_hasHaramRelationship(text)) {
      return {
        'category': 'Haram Relationships',
        'score': 100,
        'severity': 'Critical',
        'reference': _getReferences('Haram Relationships'),
        'explanation': 'Detected potential haram relationship context'
      };
    }

    if (_isLowValueAction(text)) {
      return {
        'category': 'Minimal Effort',
        'score': 5,
        'severity': 'Low Reward',
        'reference': 'Hadith: "Actions are by intentions" (Bukhari)',
        'explanation': 'Action detected as superficial without real impact'
      };
    }

    var majorResult = _analyzeCategory(text, badDeedsCategories['Major Sins (Kabair)']!, 'Major Sins (Kabair)', 100, isGood: false);
    if (majorResult['score'] > 0) {
      if (isNegated) return _flipToGood(majorResult);
      return majorResult
        ..['severity'] = 'Critical'
        ..['reference'] = _getReferences('Major Sins (Kabair)');
    }

    var goodResult = _findBestCategory(text, goodDeedsCategories, isGood: true);
    if (goodResult['score'] >= 3) {
      if (isNegated) return _flipToBad(goodResult);
      return goodResult
        ..['severity'] = 'High Reward'
        ..['reference'] = _getReferences(goodResult['category']);
    }

    var badResult = _findBestCategory(text, badDeedsCategories, isGood: false);
    if (badResult['score'] >= 2) {
      if (isNegated) return _flipToGood(badResult);
      return badResult
        ..['severity'] = badResult['category'].contains('Major') ? 'Critical' : 'Warning'
        ..['reference'] = _getReferences(badResult['category']);
    }

    return {
      'category': 'Uncategorized',
      'score': 0,
      'severity': 'Neutral',
      'reference': 'Quran 99:7-8 - Whoever does an atom\'s weight of good will see it, and whoever does an atom\'s weight of evil will see it.',
      'explanation': 'No strong match found - please describe in more detail'
    };
  }

