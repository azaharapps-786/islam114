    List<String> words = processed.split(' ');
    words = words.where((word) => !stopWords.contains(word) && word.isNotEmpty).toList();
    return words.join(' ');
  }

  static bool _hasHaramRelationship(String text) {
    final patterns = [
      r'\b(girlfriend|boyfriend|date|flirt|secret relationship|pre marital|extramarital|affair|cheating|emotional affair|online dating|tinder|bumble|haram crush)\b',
      r'\bhelped girlfriend\b',
      r'\bhelped boyfriend\b',
      r'\bgave to girlfriend\b',
      r'\bspent time with boyfriend\b'
    ];
    return patterns.any((pattern) => RegExp(pattern, caseSensitive: false).hasMatch(text));
  }

  static bool _isLowValueAction(String text) {
    final patterns = [
      r'\bliked islamic video\b',
      r'\bwatched youtube islam\b',
      r'\bshared post\b',
      r'\bcommented islamic\b',
      r'\bfollowed islamic account\b',
      'liked 50 videos',
      'scrolled islamic content'
    ];
    return patterns.any((pattern) => RegExp(pattern, caseSensitive: false).hasMatch(text));
  }

  static Map<String, dynamic> _analyzeCategory(String text, List<String> keywords, String category, int baseScore, {required bool isGood}) {
    int score = 0;
    for (String keyword in keywords) {
      if (text.contains(keyword)) {
        score += keyword.split(' ').length * baseScore;
      }
    }
    return {'category': category, 'score': score};
  }

  static Map<String, dynamic> _findBestCategory(String text, Map<String, List<String>> categories, {required bool isGood}) {
    Map<String, dynamic> best = {'category': 'Uncategorized', 'score': 0};
    categories.forEach((category, keywords) {
      var result = _analyzeCategory(text, keywords, category, 10, isGood: isGood);
      if (result['score'] > best['score']) {
        best = result;
      }
    });
    return best;
  }

  static Map<String, dynamic> _flipToGood(Map<String, dynamic> badResult) {
    return {
      'category': 'Avoided ${badResult['category']}',
      'score': badResult['score'] ~/ 2,
      'severity': 'Reward for Restraint',
      'reference': 'Quran 16:96 - "What is with you must vanish: what is with Allah will endure"',
      'explanation': 'Detected negation of bad deed - turned to good'
    };
  }

  static Map<String, dynamic> _flipToBad(Map<String, dynamic> goodResult) {
    return {
      'category': 'Missed ${goodResult['category']}',
      'score': goodResult['score'],
      'severity': 'Warning',
      'reference': 'Hadith: "The deeds are considered by the intentions" (Bukhari)',
      'explanation': 'Detected negation of good deed - turned to missed opportunity'
    };
  }

  // Fixed: Added the missing method
  static String _getReferences(String category) {
    final refs = references[category] ?? [];
    if (refs.isEmpty) return 'Keep seeking Allah\'s forgiveness and guidance.';
    return refs.join('\n\n');
  }

  // ===================== PUBLIC UTILS =====================
  static String getCategory(String text) => analyzeText(text)['category'] as String;
  static String getReference(String text) => analyzeText(text)['reference'] as String;
  static String getExplanation(String text) => analyzeText(text)['explanation'] as String;
  static int getSeverityScore(String text) {
    var result = analyzeText(text);
    switch (result['severity']) {
      case 'Critical': return 100;
      case 'High Reward': return -80;
      case 'Warning': return 40;
      case 'Low Reward': return -20;
      default: return 0;
    }
  }
